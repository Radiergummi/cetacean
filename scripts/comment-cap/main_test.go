package main

import (
	"go/parser"
	"go/token"
	"testing"
)

func TestOverlongCountsCommentLinesNotDirectives(t *testing.T) {
	const src = `package p

// Four lines are the cap,
//
// blank comment lines included,
// and the one before a directive is not.
//
//go:noinline
func ok() {}

// Five lines
// is one
// too
// many
// here.
func long() {}

/* A block
comment
counts
by its
lines. */
var v int

func f() {
	// Inside a body too,
	// and a group ends
	// at a blank line.

	// So this is a second group.
	_ = 0
}
`

	fset := token.NewFileSet()

	file, err := parser.ParseFile(fset, "p.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}

	got := overlong(fset, file)

	want := []int{11, 18}
	if len(got) != len(want) {
		t.Fatalf("overlong() = %v, want blocks at lines %v", got, want)
	}

	for i, block := range got {
		if block.line != want[i] {
			t.Errorf("block %d at line %d, want %d", i, block.line, want[i])
		}
	}
}

func TestOverlongSkipsGeneratedFiles(t *testing.T) {
	const src = "// Code generated by x. DO NOT EDIT.\n\n// a\n// b\n// c\n// d\n// e\npackage p\n"

	fset := token.NewFileSet()

	file, err := parser.ParseFile(fset, "p.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}

	if got := overlong(fset, file); len(got) != 0 {
		t.Errorf("overlong(generated) = %v, want none", got)
	}
}
